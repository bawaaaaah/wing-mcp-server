export interface WingGlyph {
  d: string;
  viewBox: string;
  /** A letter or two drawn over the glyph, for ids the console tells apart only by a letter. */
  badge?: string;
  /** Holes in the shape are cut with the even-odd fill rule. */
  evenodd?: boolean;
}

const MDI_VIEWBOX = "0 0 24 24";
const mdi = (d: string, badge?: string): WingGlyph => ({ d, viewBox: MDI_VIEWBOX, badge });
const game = (d: string, badge?: string): WingGlyph => ({ d, viewBox: GAME_ICONS_VIEWBOX, badge });
const own = (name: keyof typeof CUSTOM_ICONS, badge?: string): WingGlyph => ({
  d: CUSTOM_ICONS[name].d,
  evenodd: CUSTOM_ICONS[name].evenodd,
  viewBox: CUSTOM_ICONS_VIEWBOX,
  badge,
});

